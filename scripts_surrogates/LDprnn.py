class LUv3_3Layer(nn.Module):
    """Concatenation-based encoder: micro_params are concatenated with strain
    and processed by a standard MLP with fixed learned parameters (nn.Dense).

    Same LU construction and bias shift as HyperLUv2_3Layer, but replaces the
    hypernetwork with direct concatenation.
    """
    n_matpts: int
    hidden_dim: int = 8
    micro_vals_used: list = None

    @nn.compact
    def __call__(self, x, micro_params):
        x_flat = jnp.stack([x[:, 0, 0], x[:, 1, 1], x[:, 0, 1]], axis=1)  # [b, 3]

        # Concatenate strain with micro parameters
        micro_input = micro_params[:, self.micro_vals_used]  # [b, k]
        mlp_input = jnp.concatenate([x_flat, micro_input], axis=1)  # [b, 3+k]

        # Build zero-strain input for bias shift (zeros for x_flat, keep micro)
        mlp_input_zero = jnp.concatenate([jnp.zeros_like(x_flat), micro_input], axis=1)  # [b, 3+k]

        dense1 = nn.Dense(features=self.hidden_dim, name="lu_dense1")
        dense2 = nn.Dense(features=self.hidden_dim, name="lu_dense2")
        dense3 = nn.Dense(features=self.hidden_dim, name="lu_dense3")
        dense_out = nn.Dense(features=self.n_matpts * 4, name="lu_dense_out")

        def mlp(inp):
            """3-hidden-layer MLP with softplus activation."""
            h = nn.softplus(dense1(inp))
            h = nn.softplus(dense2(h))
            h = nn.softplus(dense3(h))
            return dense_out(h)

        # Bias shift: MLP(x||micro) - MLP(0||micro) ensures zero strain → zero output
        params_flat = mlp(mlp_input) - mlp(mlp_input_zero)  # [b, n_matpts*4]
        lu_params = params_flat.reshape(-1, self.n_matpts, 4)  # [b, m, 4]

        def construct_C_micro(param_vector):
            """Construct C_micro = L @ U from 4 parameters."""
            l21, u11, u12, u22 = param_vector
            L = jnp.array([[1.0, 0.0],
                          [l21, 1.0]])
            U = jnp.array([[nn.elu(u11) + 1.0, u12],
                          [0.0, nn.elu(u22) + 1.0]])
            return L @ U
        C_micro = jax.vmap(jax.vmap(construct_C_micro))(lu_params)  # [b, m, 2, 2]
        return C_micro


