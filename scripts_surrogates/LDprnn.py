def _max_eigenvalue_2x2_spd(W):
    """Compute λ_max of a 2x2 symmetric positive definite matrix (closed-form)."""
    a, b, c = W[0, 0], W[0, 1], W[1, 1]
    return 0.5 * (a + c + jnp.sqrt((a - c) ** 2 + 4 * b ** 2))


def _construct_cholesky_weight_matrix(params, w_max):
    L = jnp.array([[jax.nn.softplus(params[0]), 0.0],
                   [params[1], jax.nn.softplus(params[2])]])
    # W = L @ L.T (symmetric positive definite), scaled to bound λ_max
    W = L @ L.T
    scale = jnp.minimum(1.0, w_max / _max_eigenvalue_2x2_spd(W))
    return W * scale


class DeformationGradientLayer(nn.Module):
    """Custom layer that transforms a [b, 2, 2] input tensor into a [b*m, 2, 2] output tensor.

    This layer multiplies the input (E^Macro) with weight matrices and adds it to an Identity
    to produce multiple deformation gradient tensors per input sample (material points).

    The weight matrices are forced to be symmetric positive definite and scaled to create a deformation gradient with positive determinant.
    """
    n_matpts: int   # m: Number of material points
    w_max: float = 1.25

    @nn.compact
    def __call__(self, x, micro_params):
        # x shape: [b, 2, 2]

        # Create Cholesky parameters with shape [m, 3] for 2x2 case
        # Each 2x2 lower triangular matrix needs 3 parameters: [l11, l21, l22]
        cholesky_params = self.param('cholesky_params',
                                     # nn.initializers.normal(stddev=0.1),
                                     nn.initializers.glorot_normal(),
                                     # nn.initializers.uniform(dtype=jnp.float32),  # NOTE: uniform distribution
                                     (self.n_matpts, 3))

        # Construct weight matrices from Cholesky parameters
        weights = jax.vmap(_construct_cholesky_weight_matrix, in_axes=(0, None))(cholesky_params, self.w_max)

        # Perform the batched matrix multiplication
        E_micro = jnp.einsum('bik,mkj->bmij', x, weights)

        # Convert E to C
        C_micro = 2 * E_micro + jnp.eye(2)

        return C_micro

class HyperDeformationGradientLayer_grad(nn.Module):
    """Hypernetwork version of DeformationGradientLayer.

    The Cholesky parameters are generated by a small neural network based on micro_params,
    allowing the deformation gradient transformation to be conditioned on material properties.
    """
    n_matpts: int   # m: Number of material points
    micro_vals_used: list = None  # Subset of micro parameters to use
    w_max: float = 1.25

    @nn.compact
    def __call__(self, x, micro_params):
        hidden = nn.Dense(features=self.n_matpts, name="hyperDefGrad_hid1", use_bias=True)(micro_params[:, self.micro_vals_used])
        hidden = nn.sigmoid(hidden)
        hidden = nn.Dense(features=self.n_matpts * 2, name="hyperDefGrad_hid2", use_bias=True)(hidden)
        hidden = nn.sigmoid(hidden)
        cholesky_params = nn.Dense(features=self.n_matpts * 3, name="hyperDefGrad_out", use_bias=True)(hidden)  # [b, 3*m]
        cholesky_params = cholesky_params.reshape(-1, self.n_matpts, 3)

        weights = jax.vmap(jax.vmap(_construct_cholesky_weight_matrix, in_axes=(0, None)), in_axes=(0, None))(cholesky_params, self.w_max)

        E_micro = jnp.einsum('bij,bmjk->bmik', x, weights)
        return 2 * E_micro + jnp.eye(2)

class HyperDeformationGradientLayer(nn.Module):
    """Hypernetwork version of DeformationGradientLayer.

    The Cholesky parameters are generated by a small neural network based on micro_params,
    allowing the deformation gradient transformation to be conditioned on material properties.
    """
    n_matpts: int   # m: Number of material points
    micro_vals_used: list = None  # Subset of micro parameters to use
    w_max: float = 1.25

    @nn.compact
    def __call__(self, x, micro_params):
        # x shape: [b, 2, 2]
        # micro_params shape: [b, k] with k the number of micro parameters

        # Hypernetwork to generate Cholesky parameters
        # Each material point needs 3 Cholesky parameters: [l11, l21, l22]
        # 3L
        # Generate weight matrix W from micro_params with hidden layers
        hidden = nn.Dense(features=self.n_matpts * 6, name="hyperDefGrad_hid1", use_bias=True)(micro_params[:, self.micro_vals_used])
        hidden = nn.sigmoid(hidden)
        hidden = nn.Dense(features=self.n_matpts * 6, name="hyperDefGrad_hid2", use_bias=True)(hidden)
        hidden = nn.sigmoid(hidden)
        cholesky_params = nn.Dense(features=3 * self.n_matpts, name="hyperDefGrad_out", use_bias=True)(hidden)  # [b, 3*m]

        # Reshape to [b, m, 3]
        cholesky_params = cholesky_params.reshape(-1, self.n_matpts, 3)

        # Apply to all batch elements and material points
        # cholesky_params: [b, m, 3] -> weights: [b, m, 2, 2]
        weights = jax.vmap(jax.vmap(_construct_cholesky_weight_matrix, in_axes=(0, None)), in_axes=(0, None))(cholesky_params, self.w_max)

        # Perform the batched matrix multiplication
        # x: [b, 2, 2], weights: [b, m, 2, 2] -> result: [b, m, 2, 2]
        E_micro = jnp.einsum('bij,bmjk->bmik', x, weights)

        # Convert E to C
        C_micro = 2 * E_micro + jnp.eye(2)

        return C_micro


