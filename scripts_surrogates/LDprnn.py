class PointLayer(nn.Module):
    """Custom decoder sparse layer with constrained connectivity pattern and weights.

    Each material point's outputs are connected to the PRNN outputs with a single weight.
    All weights are positive and sum to one.
    We assume voigt notation
    """
    n_matpts: int   # m: Number of material points

    @nn.compact
    def __call__(self, x, micro_params):
        # x shape: [b, m, o]

        # Create unconstrained weights parameter
        raw_weights = self.param('raw_weights',
                                 nn.initializers.uniform(dtype=jnp.float32),    # NOTE: uniform distribution
                                 # nn.initializers.glorot_normal(dtype=jnp.float32),    # not supported for 1D
                                 (self.n_matpts,))  # [m]

        # Apply softplus to ensure weights are positive
        weights = nn.softplus(raw_weights)  # [m]
        # Scale weights to sum to one
        weights = weights / jnp.sum(weights)  # [m]

        # Compute point wise
        output = jnp.einsum('bmo,m->bo', x, weights)  # [b, n, o]

        return output


class HyperPointLayer(nn.Module):
    """
    Hypernetwork for the PointLayer
    the weights of the PointLayer are generated by a small neural network based on micro_params.
    """
    hidden_features: int = 5
    mat_pts: int = 10   # m: number of outputs of the hypernet
    micro_vals_used: list = None

    @nn.compact
    def __call__(self, x, micro_params):
        # x shape: [b, m, o]
        # micro_params shape: [b, k] with k the number of micro parameters. Only subset micro_vals_used is used.

        # 2L
        # hyp_l1 = nn.relu(nn.Dense(features=self.hidden_features, name="point_hypernet_0", use_bias=True)(micro_params))
        # param_vector = nn.Dense(features=self.mat_pts, name="point_hypernet_1", use_bias=True)(hyp_l1)

        # 1L
        param_vector = nn.Dense(features=self.mat_pts, name="point_hypernet", use_bias=True)(micro_params[:, self.micro_vals_used])

        # Point layer operation
        # Apply softplus to ensure weights are positive
        weights = nn.softplus(param_vector)  # [b,m]
        # Scale weights to sum to one
        weights = weights / jnp.sum(weights, axis=1, keepdims=True)  # [b,m]

        output = jnp.einsum('bmo,bm->bo', x, weights)

        return output


