        # x shape: [b, 2, 2]
        centered_micro_params = micro_params[:, self.micro_vals_used] - self.micro_params_base[jnp.array(self.micro_vals_used)]

        # # Linear version (single Dense, no bias)
        delta = nn.Dense(features=self.n_matpts * 3, use_bias=False, name="residual_encoder", kernel_init=nn.initializers.normal(stddev=1e-3))(centered_micro_params)  # [b, m*3]

        # # Nonlinear version: hidden layer + small output init for near-zero start
        # n_out = self.n_matpts * 3
        # hidden = nn.Dense(features=n_out, name="residual_enc_h1")(centered_micro_params)
