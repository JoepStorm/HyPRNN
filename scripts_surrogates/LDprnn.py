class LUv2Layer(nn.Module):
    """Standard (non-hyper) LUv2 encoder layer.

    A 1-hidden-layer MLP maps strain to LU parameters per material point.
    Uses bias shift (MLP(x) - MLP(0)) to ensure zero strain -> identity.
    Same inner MLP architecture as HyperLUv2Layer, but with fixed learned weights.
    """
    n_matpts: int
    hidden_dim: int = 8

    @nn.compact
    def __call__(self, x, micro_params):
        x_flat = jnp.stack([x[:, 0, 0], x[:, 1, 1], x[:, 0, 1]], axis=1)  # [b, 3]

        dense1 = nn.Dense(features=self.hidden_dim, name="lu_dense1")
        dense_out = nn.Dense(features=self.n_matpts * 4, name="lu_dense_out")

        def mlp(inp):
            h = nn.softplus(dense1(inp))
            return dense_out(h)

        # Bias shift: MLP(x) - MLP(0) to ensure 0 in = 0 out
        params_flat = mlp(x_flat) - mlp(jnp.zeros_like(x_flat))  # [b, n_matpts*4]
        lu_params = params_flat.reshape(-1, self.n_matpts, 4)  # [b, m, 4]

        def construct_C_micro(param_vector):
            """Construct C_micro = L @ U from 4 parameters.
            L is lower unit triangular (1s on diagonal), U has elu+1 on diagonal.
            """
            l21, u11, u12, u22 = param_vector
            L = jnp.array([[1.0, 0.0],
                          [l21, 1.0]])
            U = jnp.array([[nn.elu(u11) + 1.0, u12],
                          [0.0, nn.elu(u22) + 1.0]])
            return L @ U

        C_micro = jax.vmap(jax.vmap(construct_C_micro))(lu_params)
        return C_micro


class ResidualHyperLUv2EncoderLayer(nn.Module):
    """Residual hypernetwork for LUv2Layer.

    Adds learned linear corrections to the frozen base MLP parameters (W1, b1, W2, b2):
    W1 = base_W1 + dW1(micro_params - micro_params_base), etc.
    Zero deviation at the base point by construction.

    Extract base params from a trained LUv2Layer:
        base_mlp_params = {
            'lu_dense1': trained_params['params']['encoder']['lu_dense1'],
            'lu_dense_out': trained_params['params']['encoder']['lu_dense_out'],
        }
    """
    n_matpts: int
    base_mlp_params: object    # dict with frozen base MLP weights from LUv2Layer
    micro_params_base: object  # [k] micro_params of the base configuration
    hidden_dim: int = 8
    micro_vals_used: list = None

    @nn.compact
    def __call__(self, x, micro_params):
        x_flat = jnp.stack([x[:, 0, 0], x[:, 1, 1], x[:, 0, 1]], axis=1)  # [b, 3]

        # Frozen base MLP params
        base_W1 = self.base_mlp_params['lu_dense1']['kernel']      # [3, hidden_dim]
        base_b1 = self.base_mlp_params['lu_dense1']['bias']        # [hidden_dim]
        base_W2 = self.base_mlp_params['lu_dense_out']['kernel']   # [hidden_dim, n_matpts*4]
        base_b2 = self.base_mlp_params['lu_dense_out']['bias']     # [n_matpts*4]

        total_mlp_params = base_W1.size + base_b1.size + base_W2.size + base_b2.size

        # Generate corrections to all MLP params from centered micro_params
        centered = micro_params[:, self.micro_vals_used] - self.micro_params_base[jnp.array(self.micro_vals_used)]
        delta_flat = nn.Dense(features=total_mlp_params, use_bias=False, name="residual_encoder", kernel_init=nn.initializers.normal(stddev=1e-3))(centered)  # [b, total_mlp_params]

        # Unpack deltas and add to frozen base params
        idx = 0
        W1 = base_W1[None] + delta_flat[:, idx:idx + base_W1.size].reshape(-1, *base_W1.shape)
        idx += base_W1.size
        b1 = base_b1[None] + delta_flat[:, idx:idx + base_b1.size].reshape(-1, *base_b1.shape)
        idx += base_b1.size
        W2 = base_W2[None] + delta_flat[:, idx:idx + base_W2.size].reshape(-1, *base_W2.shape)
        idx += base_W2.size
        b2 = base_b2[None] + delta_flat[:, idx:idx + base_b2.size].reshape(-1, *base_b2.shape)

        # Forward pass through corrected MLP (batched, since W1..b2 are now per-sample)
        def mlp_forward(inp):
            h = nn.softplus(jnp.einsum('bi,bij->bj', inp, W1) + b1)
            return jnp.einsum('bi,bij->bj', h, W2) + b2

        # Bias shift: MLP(x) - MLP(0) to ensure 0 in = 0 out
        params_flat = mlp_forward(x_flat) - mlp_forward(jnp.zeros_like(x_flat))
        lu_params = params_flat.reshape(-1, self.n_matpts, 4)  # [b, m, 4]

        def construct_C_micro(param_vector):
            l21, u11, u12, u22 = param_vector
            L = jnp.array([[1.0, 0.0],
                          [l21, 1.0]])
            U = jnp.array([[nn.elu(u11) + 1.0, u12],
                          [0.0, nn.elu(u22) + 1.0]])
            return L @ U

        C_micro = jax.vmap(jax.vmap(construct_C_micro))(lu_params)
        return C_micro

class HyperLUv2Layer(nn.Module):
    """
    Version 2:
    - reduced nonlinearity in the LU itself, by using lower unit triangle
    - Increased generality to allow bias & arbitrary activations while ensuring 0 in = 0 out, by using a bias shift (out = MLP(x) - MLP(0))
    """
    n_matpts: int
    hidden_dim: int = 8
    micro_vals_used: list = None

    @nn.compact
    def __call__(self, x, micro_params):
        x_flat = jnp.stack([x[:, 0, 0], x[:, 1, 1], x[:, 0, 1]], axis=1)  # [b, 3]

        # Hypernetwork generates weights and biases for the 2-layer network
        # Layer 1: W1 [3, hidden_dim], b1 [hidden_dim]
        # Layer 2: W2 [hidden_dim, n_matpts*6], b2 [n_matpts*4]
        n_params_W1 = 3 * self.hidden_dim
        n_params_b1 = self.hidden_dim
        n_params_W2 = self.hidden_dim * self.n_matpts * 4
        n_params_b2 = self.n_matpts * 4
